import assert from 'node:assert/strict';
import fs from 'node:fs';
const file=new URL('../public/data/route-review/origin-entries.json',import.meta.url);
assert.ok(fs.existsSync(file),'48개 원점의 진입 후보 자료가 있어야 한다');
const data=JSON.parse(fs.readFileSync(file));
const {entryFeatures,filterOrigins,originCards}=await import('../src/origin-entry-core.js');
const {mapFeature}=await import('../src/point-review-core.js');
assert.equal(data.origins.length,48);
assert.equal(new Set(data.origins.map(o=>o.id)).size,48);
assert.equal(data.origins.filter(o=>o.hourly_status==='available').length,28);
assert.equal(data.origins.filter(o=>o.hourly_status==='missing').length,20);
assert.equal(data.origins.filter(o=>o.type==='PARKING').length,19);
assert.equal(data.origins.filter(o=>o.entry_ids.length===0).length,2);
assert.ok(data.origins.every(o=>o.user_approved===false&&o.routing_enabled===false&&o.allocation_weight===null));
assert.ok(data.origins.filter(o=>o.type==='PARKING').every(o=>o.pedestrian_exit===null));
for(const id of ['STN-SEOUL-GTX','STN-SEOUL-GYEONGUI'])assert.equal(data.origins.find(o=>o.id===id).status,'boundary_missing');
for(const o of data.origins)for(const id of o.entry_ids)assert.ok(data.entries.some(e=>e.id===id),id);
for(const e of data.entries)assert.ok(data.origins.some(o=>o.entry_ids.includes(e.id)),e.id);
const features=entryFeatures(data);
assert.equal(new Set(features.map(f=>f.review_id)).size,features.length);
assert.ok(features.length>10&&features.length<48);
assert.ok(features.every(f=>f.layer==='od'&&f.record_kind==='entry_candidate'&&f.user_approved===false&&f.routing_enabled===false));
assert.ok(features.every(f=>mapFeature(f)));
assert.ok(features.some(f=>f.floor==='B1')&&features.some(f=>f.floor==='B3')&&features.some(f=>f.floor==='2F'));
assert.ok(features.some(f=>f.origin_ids.length>1));
assert.ok(data.entries.filter(e=>!e.map_eligible).every(e=>!features.some(f=>f.review_id===e.id)));
assert.equal(filterOrigins(data,{query:'02003'}).length,1);
assert.equal(filterOrigins(data,{query:'GTX'}).length,1);
assert.equal(filterOrigins(data,{query:'서울스퀘어'}).length,2); // bus stop and parking are distinct origins
assert.equal(filterOrigins(data,{type:'PARKING'}).length,19);
const html=originCards(data,{query:'GTX'});
assert.ok(html.includes('접속부 위치 확인 필요')&&html.includes('시간대 미확보'));
assert.ok(!html.includes('undefined'));
const hostile=structuredClone(data);hostile.origins[0].name='<img src=x onerror=alert(1)>';
assert.ok(!originCards(hostile,{}).includes('<img src=x'));
assert.ok(data.hourly.source_summary.included_monthly_events===12410020);
assert.equal(data.hourly.new_values_generated,false);
assert.equal(data.models.gtx.numeric_finalized,false);
assert.equal(data.models.parking.numeric_finalized,false);
console.log(`PASS 48 origins, 28 existing hourly / 20 missing, ${features.length} shared green candidates, no route approval, no invented GTX/Gyeongui boundary.`);
